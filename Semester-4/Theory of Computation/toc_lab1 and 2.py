# Function to find epsilon closure
def epsilon_closure(states):
    closure = set(states)
    stack = list(states)

    while stack:
        state = stack.pop()
        if (state, 'e') in transitions:
            for nxt in transitions[(state, 'e')]:
                if nxt not in closure:
                    closure.add(nxt)
                    stack.append(nxt)
    return closure

